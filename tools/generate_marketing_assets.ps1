function Escape-Xml {
  param([string]$Text)
  if ($null -eq $Text) { return '' }
  return [System.Security.SecurityElement]::Escape($Text)
}

function Get-ExcelColumnName {
  param([int]$Number)
  $name = ''
  while ($Number -gt 0) {
    $mod = ($Number - 1) % 26
    $name = [char](65 + $mod) + $name
    $Number = [math]::Floor(($Number - $mod) / 26)
  }
  return $name
}

function New-WorksheetXml {
  param(
    [string]$SheetName,
    [object[][]]$Rows
  )

  $sb = New-Object System.Text.StringBuilder
  [void]$sb.Append('<?xml version="1.0" encoding="UTF-8" standalone="yes"?>')
  [void]$sb.Append('<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>')

  for ($r = 0; $r -lt $Rows.Count; $r++) {
    $rowNumber = $r + 1
    [void]$sb.Append("<row r=""$rowNumber"">")
    $row = $Rows[$r]
    for ($c = 0; $c -lt $row.Count; $c++) {
      $value = $row[$c]
      if ($null -eq $value -or $value -eq '') { continue }
      $cellRef = "$(Get-ExcelColumnName ($c + 1))$rowNumber"
      $escaped = Escape-Xml ([string]$value)
      [void]$sb.Append("<c r=""$cellRef"" t=""inlineStr""><is><t xml:space=""preserve"">$escaped</t></is></c>")
    }
    [void]$sb.Append('</row>')
  }

  [void]$sb.Append('</sheetData></worksheet>')
  return $sb.ToString()
}

function New-XlsxWorkbook {
  param(
    [string]$Path,
    [System.Collections.Specialized.OrderedDictionary]$Sheets
  )

  Add-Type -AssemblyName System.IO.Compression.FileSystem

  $tempRoot = Join-Path $env:TEMP ("vector_xlsx_" + [guid]::NewGuid().ToString('N'))
  $null = New-Item -ItemType Directory -Path $tempRoot
  $null = New-Item -ItemType Directory -Path (Join-Path $tempRoot '_rels')
  $null = New-Item -ItemType Directory -Path (Join-Path $tempRoot 'xl')
  $null = New-Item -ItemType Directory -Path (Join-Path $tempRoot 'xl\_rels')
  $null = New-Item -ItemType Directory -Path (Join-Path $tempRoot 'xl\worksheets')

  $sheetOverrides = @()
  $sheetRefs = @()
  $sheetRels = @()
  $sheetIndex = 1

  foreach ($sheetName in $Sheets.Keys) {
    $sheetFile = "sheet$sheetIndex.xml"
    $sheetId = $sheetIndex
    $sheetRid = "rId$sheetIndex"
    $sheetOverrides += "<Override PartName=""/xl/worksheets/$sheetFile"" ContentType=""application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml""/>"
    $sheetRefs += "<sheet name=""$(Escape-Xml $sheetName)"" sheetId=""$sheetId"" r:id=""$sheetRid""/>"
    $sheetRels += "<Relationship Id=""$sheetRid"" Type=""http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet"" Target=""worksheets/$sheetFile""/>"
    $xml = New-WorksheetXml -SheetName $sheetName -Rows $Sheets[$sheetName]
    Set-Content -Path (Join-Path $tempRoot "xl\worksheets\$sheetFile") -Value $xml -Encoding UTF8
    $sheetIndex++
  }

  $contentTypes = @"
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
  <Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
  <Default Extension="xml" ContentType="application/xml"/>
  <Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>
  <Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>
  $($sheetOverrides -join "`n  ")
</Types>
"@

  $rootRels = @"
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  <Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>
</Relationships>
"@

  $workbook = @"
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
  <sheets>
    $($sheetRefs -join "`n    ")
  </sheets>
</workbook>
"@

  $workbookRels = @"
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
  $($sheetRels -join "`n  ")
  <Relationship Id="rIdStyles" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>
</Relationships>
"@

  $styles = @"
<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<styleSheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main">
  <fonts count="1"><font><sz val="11"/><name val="Calibri"/></font></fonts>
  <fills count="1"><fill><patternFill patternType="none"/></fill></fills>
  <borders count="1"><border/></borders>
  <cellStyleXfs count="1"><xf/></cellStyleXfs>
  <cellXfs count="1"><xf xfId="0"/></cellXfs>
  <cellStyles count="1"><cellStyle name="Normal" xfId="0" builtinId="0"/></cellStyles>
</styleSheet>
"@

  Set-Content -Path (Join-Path $tempRoot '[Content_Types].xml') -Value $contentTypes -Encoding UTF8
  Set-Content -Path (Join-Path $tempRoot '_rels\.rels') -Value $rootRels -Encoding UTF8
  Set-Content -Path (Join-Path $tempRoot 'xl\workbook.xml') -Value $workbook -Encoding UTF8
  Set-Content -Path (Join-Path $tempRoot 'xl\_rels\workbook.xml.rels') -Value $workbookRels -Encoding UTF8
  Set-Content -Path (Join-Path $tempRoot 'xl\styles.xml') -Value $styles -Encoding UTF8

  if (Test-Path $Path) { Remove-Item $Path -Force }
  [System.IO.Compression.ZipFile]::CreateFromDirectory($tempRoot, $Path)
  Remove-Item $tempRoot -Recurse -Force
}

function Get-Length {
  param([string]$Text)
  if ($null -eq $Text) { return 0 }
  return $Text.Length
}

function Add-SemanticRows {
  param(
    [ref]$Rows,
    [string]$Group,
    [string]$Cluster,
    [string]$Landing,
    [string]$Priority,
    [string]$Comment,
    [string[]]$Bases,
    [string[]]$Variants
  )

  foreach ($base in $Bases) {
    foreach ($variant in $Variants) {
      $keyword = if ([string]::IsNullOrWhiteSpace($variant)) { $base } else { "$base $variant" }
      $Rows.Value.Add(@($Group, $Cluster, $keyword.Trim(), 'Коммерческий', $Landing, $Priority, $Comment))
    }
  }
}

